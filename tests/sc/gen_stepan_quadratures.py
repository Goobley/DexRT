"""Generate source/ScStepanQuadratures.hpp from the Stepan et al. 2020 (A&A
636, A24) "near optimal unpolarised" octant tables shipped with Lightweaver."""
import sys
from pathlib import Path
import numpy as np

root = Path(__file__).resolve().parents[2]
table_dir = root / "Lw/Lightweaver/Utils/J_A+A_636_A24"
orders = [3, 7, 9, 11, 13, 15]
names = {3: "il3n1", 7: "il7n3", 9: "il9n6", 11: "il11n7", 13: "il13n10", 15: "il15n11"}

out = []
out.append("#if !defined(DEXRT_SC_STEPAN_QUADRATURES_HPP)")
out.append("#define DEXRT_SC_STEPAN_QUADRATURES_HPP")
out.append("// NOTE: Generated by tests/sc/gen_stepan_quadratures.py -- do not edit.")
out.append("// Stepan et al. 2020 (A&A 636, A24) octant quadratures: [weight, theta_deg, chi_deg],")
out.append("// weights summing to 1/8 per octant.")
out.append("")
out.append("struct ScStepanOctantEntry {")
out.append("    double weight;")
out.append("    double theta_deg;")
out.append("    double chi_deg;")
out.append("};")
out.append("")
for o in orders:
    data = np.atleast_2d(np.genfromtxt(table_dir / f"{names[o]}.dat"))
    out.append(f"constexpr ScStepanOctantEntry SC_STEPAN_{names[o].upper()}[] = {{")
    for row in data:
        out.append(f"    {{{float(row[0])!r}, {float(row[1])!r}, {float(row[2])!r}}},")
    out.append("};")
    out.append("")
out.append("struct ScStepanTable {")
out.append("    int order;")
out.append("    int num_points;")
out.append("    const ScStepanOctantEntry* data;")
out.append("};")
out.append("")
out.append("constexpr ScStepanTable SC_STEPAN_TABLES[] = {")
for o in orders:
    n = names[o].upper()
    out.append(f"    {{{o}, int(sizeof(SC_STEPAN_{n}) / sizeof(ScStepanOctantEntry)), SC_STEPAN_{n}}},")
out.append("};")
out.append("")
out.append("#else")
out.append("#endif")
(root / "source/ScStepanQuadratures.hpp").write_text("\n".join(out) + "\n")
